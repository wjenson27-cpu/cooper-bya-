export function fmtTime(seconds) {
  const s = Math.max(0, Math.floor(seconds));
  const m = Math.floor(s / 60);
  const r = s % 60;
  return m + ":" + String(r).padStart(2, "0");
}

export function starCount(level, time, squirrelsCaught) {
  let stars = 1;
  if (time <= level.par) stars += 1;
  const total = level.squirrels.length;
  if (total === 0 || squirrelsCaught >= total) stars += 1;
  return stars;
}
